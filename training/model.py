"""Frozen MGO1 encoder and little-endian float32 model interchange; NumPy only."""
import hashlib
import json
import struct
from pathlib import Path
import numpy as np

SCHEMA = 'metagross_observation_v1/MGO1'
ENCODER = 'mgo1_residual_v1'
DIMS = (415, 64, 32)
SHAPES = [(64, 415), (64,), (32, 64), (32,), (5, 32), (5,), (1, 32), (1,)]
NAMES = ['w1', 'b1', 'w2', 'b2', 'wp', 'bp', 'wv', 'bv']
SCALES = np.ones(181, dtype=np.float32)
SCALES[0:3] = [100, 2, 1]
for s in (3, 13):
    SCALES[s:s+10] = [400, 1, 18, 18, 256, 256, 256, 256, 256, 256]
SCALES[23:31] = 256
SCALES[31:37] = 6
SCALES[37:48] = [2, 2, 256, 10, 1, 1, 1, 3, 17, 17, 100]
for s in range(48,64,4): SCALES[s:s+4] = [1,1,20,20]
SCALES[64:79] = [100,1,6,6,6,6,6,6,1,1,1,10,1,1,1]
for s in range(79,111,8): SCALES[s:s+8] = [1,1,100,100,100,1,20,20]
SCALES[111:124] = [1,1,2,1,1,3,1,17,5,1,1,1,1]
SCALES[142:154] = [4,1,17,1,17,3,1,1,1,100,100,100]
for s in (154,160): SCALES[s:s+6] = [1,17,1,17,4,1]
SCALES[166:170] = 256
SCALES[171:175] = 100
ZERO = [42, 77, 78, 112, 114, 117] + list(range(49,64,4)) + list(range(80,111,8))

def encode(obs):
    obs = np.asarray(obs, dtype=np.int32)
    x = np.clip(obs[:,:181].astype(np.float32) / SCALES, -1, 1)
    x[:,ZERO] = 0
    parts = [x]
    for s,valid in [(49+4*i,48+4*i) for i in range(4)] + [(80+8*i,79+8*i) for i in range(4)]:
        parts.append(((obs[:,s,None] == np.arange(17)) & (obs[:,valid,None] != 0)).astype(np.float32))
    parts.append((obs[:,42,None] == np.arange(35)).astype(np.float32))
    parts.append(((obs[:,112,None] == np.arange(35)) & (obs[:,111,None] != 0)).astype(np.float32))
    for s,n in [(117,18),(114,4),(77,3),(78,3)]:
        parts.append(((obs[:,s,None] >> np.arange(n)) & 1).astype(np.float32))
    out = np.concatenate(parts,axis=1)
    assert out.shape[1] == DIMS[0]
    return out

def save_model(path, arrays, prior=2.):
    payload = b''.join(np.asarray(a,dtype='<f4').tobytes() for a in arrays) + struct.pack('<f',prior)
    Path(path).write_bytes(struct.pack('<4sIII',b'MWP1',*DIMS)+payload)
    return hashlib.sha256(payload).hexdigest()

def load_model(path):
    data = Path(path).read_bytes()
    if struct.unpack('<4sIII',data[:16]) != (b'MWP1',*DIMS): raise ValueError('model dimensions/magic')
    vals = np.frombuffer(data[16:],dtype='<f4')
    if len(vals) != sum(np.prod(s) for s in SHAPES)+1 or not np.isfinite(vals).all(): raise ValueError('model payload')
    arrays=[]; off=0
    for shape in SHAPES:
        size=int(np.prod(shape)); arrays.append(vals[off:off+size].reshape(shape).copy()); off+=size
    return arrays,float(vals[-1]),hashlib.sha256(data[16:]).hexdigest()

def export_header(model, header):
    arrays,prior,digest=load_model(model)
    def literal(v):
        s=format(float(v),'.9g')
        return s+('f' if '.' in s or 'e' in s else '.0f')
    lines=['// Generated by training/model.py; do not edit.',f'#define LEARNED_SCHEMA "{SCHEMA}"',f'#define LEARNED_ENCODER "{ENCODER}"',f'#define LEARNED_SHA256 "{digest}"','static const LearnedWeights learned_default = {']
    for a in arrays:
        flat=a.ravel(); lines.append('  {')
        for i in range(0,len(flat),12): lines.append('    '+','.join(literal(v) for v in flat[i:i+12])+',')
        lines.append('  },')
    lines += ['  '+literal(prior),'};','']
    Path(header).write_text('\n'.join(lines))
    Path(str(header)+'.json').write_text(json.dumps(dict(schema=SCHEMA,encoder=ENCODER,sha256=digest,dimensions=DIMS,prior=prior),indent=2)+'\n')

def init(path):
    rng=np.random.default_rng(73103)
    arrays=[]
    for name,shape in zip(NAMES,SHAPES):
        a=(rng.normal(0,np.sqrt(2/shape[1]),shape).astype(np.float32) if len(shape)==2 else np.zeros(shape,np.float32))
        if name in ('wp','wv'): a*=0
        arrays.append(a)
    save_model(path,arrays)

if __name__=='__main__':
    import argparse
    p=argparse.ArgumentParser(); p.add_argument('action',choices=['init','export','scales']); p.add_argument('model'); p.add_argument('header',nargs='?'); a=p.parse_args()
    if a.action=='init': init(a.model)
    elif a.action=='export': export_header(a.model,a.header)
    else: Path(a.model).write_text('static const float learned_scale[181] = {'+','.join(str(float(x))+'f' for x in SCALES)+'};\n')
